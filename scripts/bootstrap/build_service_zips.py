"""
Builds data/service-area-zips.json from the client's service-area spreadsheet.

Source (data/_source/service-area-zips.xlsx), one sheet, two column pairs:
    C/D = ZIP / State  (Virginia)        E/F = ZIP / State  (Maryland)
ZIPs are stored as numbers (22405.0), so values are cast through float -> int
and zero-padded back to 5 digits.

The generator refuses to write anything structurally unsafe: a non-integer or
non-5-digit ZIP, a duplicate, a ZIP listed under both states, or a row whose
State cell disagrees with its column. It does NOT enforce 156/159 - the client
will edit this list - but it prints the counts so a change is impossible to miss.

    python3 scripts/bootstrap/build_service_zips.py
"""
import json, re, sys, zipfile, xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "_source" / "service-area-zips.xlsx"
OUT = ROOT / "data" / "service-area-zips.json"
NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
COLUMNS = {"VA": ("C", "D"), "MD": ("E", "F")}
FIRST_DATA_ROW = 3  # rows 1-2 are the title and the ZIP/State headers


def read_cells(path: Path) -> dict[str, str]:
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        root = ET.fromstring(z.read("xl/sharedStrings.xml"))
        shared = ["".join(t.text or "" for t in si.iter(NS + "t")) for si in root.iter(NS + "si")]
    sheet = ET.fromstring(z.read("xl/worksheets/sheet1.xml"))
    cells = {}
    for c in sheet.iter(NS + "c"):
        v = c.find(NS + "v")
        if v is not None:
            cells[c.get("r")] = shared[int(v.text)] if c.get("t") == "s" else v.text
    return cells


def main() -> int:
    cells = read_cells(SRC)
    rows = sorted({int(re.sub(r"\D", "", ref)) for ref in cells})
    found: dict[str, list[str]] = {"VA": [], "MD": []}
    problems: list[str] = []

    for r in rows:
        if r < FIRST_DATA_ROW:
            continue
        for state, (zcol, scol) in COLUMNS.items():
            z, s = cells.get(f"{zcol}{r}"), cells.get(f"{scol}{r}")
            if z is None and s is None:
                continue
            if z is None or s is None:
                problems.append(f"row {r} {state}: ZIP/State cell missing (zip={z!r}, state={s!r})")
                continue
            if s.strip() != state:
                problems.append(f"row {r}: state cell {s!r} sits in the {state} column")
            try:
                f = float(z)
            except ValueError:
                problems.append(f"row {r} {state}: ZIP {z!r} is not numeric")
                continue
            if f != int(f):
                problems.append(f"row {r} {state}: ZIP {z!r} is not a whole number")
                continue
            zip5 = f"{int(f):05d}"
            if not re.fullmatch(r"\d{5}", zip5):
                problems.append(f"row {r} {state}: {z!r} is not a 5-digit ZIP")
                continue
            found[state].append(zip5)

    allzips = found["VA"] + found["MD"]
    for zip5, n in Counter(allzips).items():
        if n > 1:
            problems.append(f"ZIP {zip5} appears {n} times")

    if problems:
        print("REFUSING TO WRITE - fix the spreadsheet:", *problems, sep="\n  - ")
        return 1

    payload = {
        "_note": "Generated by scripts/bootstrap/build_service_zips.py from data/_source/service-area-zips.xlsx. "
                 "The client's approved service territory: a lead-form ZIP must be in this list to be accepted. "
                 "Do not hand-edit - update the spreadsheet and re-run the script.",
        "counts": {"va": len(found["VA"]), "md": len(found["MD"]), "total": len(allzips)},
        "va": sorted(found["VA"]),
        "md": sorted(found["MD"]),
    }
    OUT.write_text(json.dumps(payload, indent=1) + "\n")
    c = payload["counts"]
    print(f"wrote {OUT.relative_to(ROOT)}: {c['va']} VA + {c['md']} MD = {c['total']} ZIPs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
